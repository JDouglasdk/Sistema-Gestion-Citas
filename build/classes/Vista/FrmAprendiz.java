// Llenar combo desde la BD
    public void llenarComboGrupos() {
        try {
            ResultSet rs = objApr.listarGrupos();
            CboCodGruApr.removeAllItems();
            CboCodGruApr.addItem("Seleccione Grupo...");
            while (rs != null && rs.next()) {
                CboCodGruApr.addItem(rs.getString("codGru"));
            }
        } catch (SQLException e) {
            System.out.println("Error al llenar grupos: " + e.getMessage());
        }
    }

    public void habilitarInicio() {
        TxtDocApr.setText("");
        TxtNomApr.setText("");
        TxtApeApr.setText("");
        TxtEmaApr.setText("");
        TxtTelProApr.setText("");
        TxtConEmeApr.setText("");
        TxtTelConEmeApr.setText("");
        CboCodGruApr.setSelectedIndex(0);
        CboEpsApr.setSelectedIndex(0);
        
        
        //Botoneria
        BtnGuardar.setEnabled(true);
        BtnBuscar.setEnabled(true);
        BtnEditar.setEnabled(false);
        BtnActualizar.setEnabled(false);
        BtnNuevo.setEnabled(true);
        BtnRegresar.setEnabled(true);

        TxtDocApr.requestFocus();
    }

    public void Capturar() {
        objApr.setDocApr(TxtDocApr.getText());
        objApr.setCodGruApr(CboCodGruApr.getSelectedItem().toString());
        objApr.setNomApr(TxtNomApr.getText());
        objApr.setApeApr(TxtApeApr.getText());
        objApr.setEmaApr(TxtEmaApr.getText());
        objApr.setEpsApr(CboEpsApr.getSelectedItem().toString());
        objApr.setTelProApr(TxtTelProApr.getText());
        objApr.setConEmeApre(TxtConEmeApr.getText());
        objApr.setTelConEmeApre(TxtTelConEmeApr.getText());
    }

    public void Guardar() {
        if (TxtDocApr.getText().trim().isEmpty() || CboCodGruApr.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(null, "Documento y Grupo son obligatorios");
        } else {
            this.Capturar();
            objApr.Guardar();
            JOptionPane.showMessageDialog(null, "Aprendiz guardado con Ã©xito");

            BtnEditar.setEnabled(false);
            BtnActualizar.setEnabled(false);

            this.habilitarInicio();
        }
    }

    public void Buscar() {
        try {
            String bus = JOptionPane.showInputDialog("Documento del Aprendiz:");
            if (bus != null && !bus.isEmpty()) {
                objApr.setDocApr(bus);
                objApr.Buscar();
                if (objApr.datosAprendiz != null && objApr.datosAprendiz.next()) {
                    TxtDocApr.setText(objApr.datosAprendiz.getString(1));
                    CboCodGruApr.setSelectedItem(objApr.datosAprendiz.getString(2));
                    TxtNomApr.setText(objApr.datosAprendiz.getString(3));
                    TxtApeApr.setText(objApr.datosAprendiz.getString(4));
                    TxtEmaApr.setText(objApr.datosAprendiz.getString(5));
                    CboEpsApr.setSelectedItem(objApr.datosAprendiz.getString(6));
                    TxtTelProApr.setText(objApr.datosAprendiz.getString(7));
                    TxtConEmeApr.setText(objApr.datosAprendiz.getString(8));
                    TxtTelConEmeApr.setText(objApr.datosAprendiz.getString(9));

                    TxtDocApr.setEditable(false);

                    //Botoneria
                    BtnGuardar.setEnabled(true);
                    BtnEditar.setEnabled(true);
                    BtnActualizar.setEnabled(true);
                    BtnBuscar.setEnabled(true);
                    BtnNuevo.setEnabled(true);

                } else {
                    JOptionPane.showMessageDialog(null, "Aprendiz no encontrado");
                }
            }
        } catch (SQLException e) {
        }
    }

    public void Editar() {
        TxtDocApr.setEditable(false);

        TxtNomApr.requestFocus();
    }

    public void Actualizar() {
        this.Capturar();
        objApr.Actualizar();
        JOptionPane.showMessageDialog(null, "Datos actualizados");
        this.habilitarInicio();
    }

    public void Regresar() {
        FrmIndex objIndex = new FrmIndex();
        objIndex.setVisible(true);
        this.dispose();
    }

